def crawler_plates(press_kpa: float, soil: int) -> str:
    """表4（22mm）: 最大接地圧 → 敷鉄板（6.0×1.5m）の枚数 "0"〜"2" か "-"（50kN/m² ごとの欄に切り上げ）."""
